// --------------------------------------------------------------------------------------- lookup
export function zh(en) {
  if (typeof en !== "string") return en;
  const key = en.trim();
  if (!key) return en;
  const hit = ZH[key];
  if (hit !== undefined) return en === key ? hit : en.replace(key, hit);
  if (key.includes(" · ")) {  // composite labels ("Profit & loss · October 2026"): translate each part
    const parts = key.split(" · "), next = parts.map(zh);
    if (next.some((p, i) => p !== parts[i])) return en.replace(key, next.join(" · "));
  }
  for (const [re, out] of ZH_PATTERNS) {
    if (re.test(key)) return out === null ? en : en.replace(key, key.replace(re, out));
  }
  return en;
}

// Chinese copy table from an English one; functions are wrapped so their output is translated too.
export function zhCopy(value) {
  if (typeof value === "string") return zh(value);
  if (typeof value === "function") return (...args) => zhCopy(value(...args));
  if (Array.isArray(value)) return value.map(zhCopy);
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).map(([k, v]) => [k, zhCopy(v)]));
  return value;
}

// ------------------------------------------------------------------------- page-level fallback
// Text the page renders that did not go through zh() (server labels, Advanced-mode details).
// User data and model output are never translated: the owner's own chat messages, the model's reply
// text, editable fields and [data-i18n-skip] subtrees. Buttons and labels around a reply still are.
const SKIP = "script,style,textarea,code,pre,[contenteditable],[data-i18n-skip],.msg.user,.msg .text";
const ATTRS = ["placeholder", "aria-label", "title"];

function translateText(node) {
  const parent = node.parentElement;
  if (!parent || parent.closest(SKIP)) return;
  const next = zh(node.nodeValue);
  if (next !== node.nodeValue) node.nodeValue = next;
}

function translateAttrs(el) {
  if (el.closest(SKIP) && !el.matches("input,textarea,select")) return;
  for (const a of ATTRS) {
    const v = el.getAttribute(a);
    if (v) { const next = zh(v); if (next !== v) el.setAttribute(a, next); }
  }
}

export function translateTree(root) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) { translateText(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  translateAttrs(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = walker.nextNode(); n; n = walker.nextNode()) {
    if (n.nodeType === Node.TEXT_NODE) translateText(n); else translateAttrs(n);
  }
}

let observer = null;
// Active only while Chinese is selected; switching language re-renders the page in that language.
export function setChineseFallback(on) {
  if (!on) { observer?.disconnect(); observer = null; return; }
  if (observer) return;
  translateTree(document.body);
  observer = new MutationObserver(records => {
    for (const r of records) {
      if (r.type === "characterData") translateText(r.target);
      else if (r.type === "attributes") translateAttrs(r.target);
      else r.addedNodes.forEach(translateTree);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
}
