// Automatic suggestions against the isolated demo database only.
import { chromium } from '../../data/ui-review/node_modules/playwright-core/index.mjs';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
execFileSync('.venv/Scripts/python.exe', ['tests/browser/seed_strategy.py'], { stdio: 'pipe' });
const browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
const context = await browser.newContext({ baseURL: 'http://127.0.0.1:8002', viewport: { width: 1280, height: 900 }, reducedMotion: 'reduce' });
await context.addInitScript(() => { localStorage.setItem('tour_done:tanvir', '1'); localStorage.setItem('more_languages', '1'); localStorage.setItem('ui_mode', 'simple'); localStorage.setItem('theme', 'light'); });
const page = await context.newPage(), errors = [];
page.on('pageerror', e => errors.push(e.message));
const fit = async () => assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
try {
  await page.goto('/'); await page.locator('#auth-username').fill('tanvir'); await page.locator('#auth-password').fill('tanvir-demo-2026'); await page.locator('.auth-submit').click();
  await page.locator('.guided-home').waitFor();
  const before = (await (await page.request.get('/api/pilot/cases')).json()).length;
  await page.locator('#nav-strategy').click(); await page.locator('.strategy-recommendation').first().waitFor();
  const data = await (await page.request.get('/api/pilot/strategy')).json();
  assert.ok(data.suggestions.length > 0 && data.suggestions.length <= 3);
  assert.equal(await page.locator('.strategy-recommendation').count(), data.suggestions.length);
  assert.equal((await (await page.request.get('/api/pilot/cases')).json()).length, before);
  assert.equal(await page.locator('.strategy-manual').getAttribute('open'), null);
  assert.equal(await page.locator('#pilot-question').count(), 0);
  const selected = data.suggestions.find(x => x.item && !x.href);
  assert.ok(selected, 'Demo stock history should produce a reviewable item suggestion');
  const card = page.locator('.strategy-recommendation').filter({ has: page.getByRole('heading', { name: selected.title.en, exact: true }) });
  await card.locator('summary').click(); await card.getByText('View supporting records', { exact: true }).waitFor();
  assert.ok((await card.locator('.strategy-evidence dd').count()) > 0); await fit();
  await page.screenshot({ path: 'data/ui-review/automatic-strategy-desktop.png', fullPage: true });
  await card.locator(':scope > a.btn').click(); await page.locator('.pilot-page').waitFor();
  const resume = page.getByRole('button', { name: 'Continue this task', exact: true });
  await page.locator('#pilot-question').or(resume).first().waitFor();
  if (await resume.isVisible()) await resume.click();
  await page.locator('#pilot-question').waitFor();
  const id = Number(new URL(page.url()).hash.split('case=')[1]);
  const saved = await (await page.request.get(`/api/pilot/cases/${id}`)).json();
  assert.equal(saved.answers.item, selected.item);
  assert.equal(saved.answers._strategy_suggestion.id, selected.id);
  assert.equal(saved.next_question.id, 'drivers');
  await page.locator('.language-toggle').selectOption('zh'); await page.getByRole('heading', { name: selected.title.zh, exact: true }).waitFor();
  await page.locator('.language-toggle').selectOption('en'); await page.getByRole('heading', { name: selected.title.en, exact: true }).waitFor();
  const paused = page.waitForResponse(r => r.url().endsWith(`/cases/${id}/control`));
  await page.getByRole('button', { name: 'Do this later', exact: true }).click(); assert.equal((await paused).status(), 200);
  await page.goto('/#strategy'); await page.locator('.strategy-recommendation').first().waitFor();
  const same = page.locator('.strategy-recommendation').filter({ has: page.getByRole('heading', { name: selected.title.en, exact: true }) });
  assert.equal(await same.getByRole('link', { name: 'Open saved plan', exact: true }).getAttribute('href'), `#strategy?case=${id}`);
  await page.setViewportSize({ width: 360, height: 800 }); await page.locator('.theme-toggle').click(); await fit();
  await page.screenshot({ path: 'data/ui-review/automatic-strategy-mobile-dark.png', fullPage: true });
  await page.locator('.language-toggle').selectOption('bn'); await page.locator('.strategy-recommendation').first().waitFor(); await fit();
  await page.screenshot({ path: 'data/ui-review/automatic-strategy-mobile-bangla.png', fullPage: true });
  await page.goto('/#dashboard'); await page.locator('.guided-home').waitFor();
  assert.equal(await page.locator('.home-main-grid > *').count(), 2);
  assert.equal(await page.locator('.strategy-recommendation').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Passed: automatic record-backed cards, evidence, no auto-created plans, preselected item, existing-plan reuse, Chinese/Bangla, mobile/dark, two-card Home.');
} finally { await browser.close(); }
