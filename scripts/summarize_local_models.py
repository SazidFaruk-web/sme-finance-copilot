"""Build benchmarks/results/local_models.md from the raw run logs.

    python scripts/summarize_local_models.py
"""
from __future__ import annotations

import json
from pathlib import Path

RES = Path(__file__).resolve().parents[1] / "benchmarks" / "results"


def _load(name: str) -> list[dict]:
    p = RES / name
    if not p.exists():
        return []
    rows = {}
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            r = json.loads(line)
            rows[r["label"]] = r  # last run of a label wins
    return list(rows.values())


def pct(v) -> str:
    return "–" if v is None else f"{v:.0%}"


def main() -> None:
    golden = _load("golden_summary.jsonl")
    speed = _load("local_llm_runs.jsonl")
    out = ["# Local models on an AMD RX 9060 XT 16 GB (llama.cpp Vulkan)", "",
           "Generated by `scripts/summarize_local_models.py` from `golden_summary.jsonl` (48-scenario golden set "
           "through the real agent loop, ground truth computed by the app's deterministic tools) and "
           "`local_llm_runs.jsonl` (speed harness with the app's real prompt). Hardware: RX 9060 XT 16 GB, "
           "Ryzen 7 3700X, 16 GB DDR4, Windows 10, llama.cpp build 10930 (Vulkan).", "",
           "## Accuracy and end-to-end speed (golden set)", "",
           "| run | tools | p50 s | mean s | tool ok | valid args | numeric | financing | hallucination | "
           "BN/Banglish lang | errors | peak VRAM | flags |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in golden:
        out.append(f"| {r['label']} | {r['tools']} | {r.get('latency_p50_s')} | {r.get('latency_mean_s')} | "
                   f"{pct(r.get('tool_call_success'))} | {pct(r.get('valid_tool_args'))} | {pct(r.get('numeric_accuracy'))} | "
                   f"{pct(r.get('financing_match'))} | {pct(r.get('hallucination_rate'))} | "
                   f"{pct(r.get('bangla_banglish_language_match'))} | {r.get('errors')} | "
                   f"{(r.get('vram_peak_mb') or 0) / 1024:.1f} GB | `{r.get('flags', '')}` |")
    out += ["", "## Raw server speed (app prompt, 3 requests)", "",
            "| run | prompt tokens | prompt tok/s | gen tok/s | cold TTFT | cached TTFT | VRAM | flags |",
            "|---|---|---|---|---|---|---|---|"]
    for r in speed:
        out.append(f"| {r['label']} | {r.get('prompt_tokens')} | {r.get('pp_tok_s')} | {r.get('tg_tok_s')} | "
                   f"{(r.get('ttft_cold_ms') or 0) / 1000:.1f} s | {(r.get('ttft_cached_ms') or 0) / 1000:.2f} s | "
                   f"{(r.get('vram_dedicated_mb') or 0) / 1024:.1f} GB | `{r.get('flags', '')}` |")
    out += ["", "Rates are fractions of applicable scenarios. p50/mean are end-to-end seconds per scenario "
            "(all model calls + tool execution). Earlier Qwen runs from before the static-prompt change are in "
            "`golden_9b_*` / `golden_14b_*` and `docs/overnight_log.md`."]
    (RES / "local_models.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"wrote {RES / 'local_models.md'} ({len(golden)} golden runs, {len(speed)} speed runs)")


if __name__ == "__main__":
    main()
